    private void crearEstudiante(){
        String estCarne = txtRegistroCarnet.getText().replace(",", "").trim();
        String estNombre = txtRegistroNombre.getText().replace(",", "").trim();
        String estCorreo = txtRegistroCorreo.getText().replace(",", "").trim();

        if (!estCarne.contains("3190-")) {
            JOptionPane.showMessageDialog(this, "El carnet no pertenece a la Facultad de Ingenieria");
            return;
        }

        if (estCorreo.contains("@") && estCorreo.contains(".") && estCorreo.indexOf("@") > 0) {
            String lineaCSV = estCarne+","+estNombre+","+estCorreo+","+"false";
            GuardarEstudiante(lineaCSV);
        }else{
            JOptionPane.showMessageDialog(this, "El correo no es válido");
        }
        
        
    }

    private void GuardarEstudiante(String lineaCSV){

        try (FileWriter fw = new FileWriter(ruta, true)){
            fw.append(lineaCSV+"\n");
        } catch (IOException e) {
            System.out.println("Ocurrio un error al escribir el CSV");
        }

        MenuCongreso.limpiarCampos(this);
        JOptionPane.showMessageDialog(this, "Estudiante Registrado");

    }
    

