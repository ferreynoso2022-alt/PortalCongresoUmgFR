    public void cargarComboBox(){
        cargarExpositores();
        DefaultComboBoxModel<Expositor> modelo = new DefaultComboBoxModel<>();
        modelo.addElement(new Expositor(0,"-Selecciona-","n/a"));

        for (Expositor exp : listaExpositores) {
            modelo.addElement(exp);
        }

        comboBoxExpositor.setModel(modelo);
        comboBoxExpositor.setSelectedIndex(0);
        cargarTabla();
    }

    private void crearConferencia(){
        Expositor expSeleccionado = (Expositor) comboBoxExpositor.getSelectedItem();
        String titulo = txtTituloConferencia.getText().trim().replace(",", "");
        String salon = txtSalon.getText().trim().replace(",", "");
        String nombreExpositor = expSeleccionado.getNombre();
        int indiceId = listaConferencias.stream().mapToInt(Conferencia::getIdConferencia).max().orElse(0) + 1;

        if (expSeleccionado.getIdExpositor() == 0) {
            JOptionPane.showMessageDialog(this, "Selecciona un Expositor");
            return;
        }

        String lineaCSV = indiceId+","+titulo+","+salon+","+nombreExpositor;
        guardarConferencia(lineaCSV);
    }

    private void guardarConferencia(String lineaCSV){

        try (FileWriter fw = new FileWriter(ruta, true)) {
            fw.append(lineaCSV+"\n");
        } catch (IOException e) {
            System.out.println("Ocurrio un error al escribir el CSV");
        }

        MenuCongreso.limpiarCampos(this);
        comboBoxExpositor.setSelectedIndex(0);
    }

    private void cargarTabla(){
        listaConferencias = Conferencia.RetornarConferencias();
        DefaultTableModel modelo = (DefaultTableModel) TablaConferencias.getModel();
        modelo.setRowCount(0);
        
        for (Conferencia conf : listaConferencias) {
            Object[] fila = {conf.getIdConferencia(),conf.getTitulo(),conf.getSalon(),conf.getExpositorAsignado()};
            modelo.addRow(fila);
        }
    }

