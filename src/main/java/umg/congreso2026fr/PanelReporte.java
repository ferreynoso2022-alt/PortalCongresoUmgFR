    private void cargarTablas(){
        listaEstudiantes = Estudiante.RetornarEstudiantes();
        DefaultTableModel tbleEst = (DefaultTableModel) tablaEstudiantes.getModel();
        DefaultTableModel tbleAus = (DefaultTableModel) tablaAusentes.getModel();
        tbleEst.setRowCount(0);
        tbleAus.setRowCount(0);

        int totalEstudiantes = 0;
        int totalAsistieron = 0;
        int totalAusentes = 0;
        
        for (Estudiante est : listaEstudiantes) {

            Object[] fila = {est.getCarne(),est.getNombre(),est.getCorreo(),est.isAsistio()};
            tbleEst.addRow(fila);

            if (est.isAsistio()== true) {
                totalAsistieron++;
            } else{
                totalAusentes++;
                Object[] filaAus ={est.getCarne(),est.getNombre()};
                tbleAus.addRow(filaAus);
            }

            totalEstudiantes++;
        }

        setLabels(totalEstudiantes, totalAsistieron, totalAusentes);
    }

    public void setLabels(int totalEstudiantes, int totalAsistieron, int totalAusentes){
        String estTotal = String.valueOf(totalEstudiantes);
        String asisTotal = String.valueOf(totalAsistieron);
        String ausTotal = String.valueOf(totalAusentes);

        labelTotalEstudiantes.setText(estTotal);
        labelAsistieron.setText(asisTotal);
        labelAusentes.setText(ausTotal);
    }

